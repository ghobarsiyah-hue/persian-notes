import { chromium } from 'playwright-core';
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('http://localhost:5173/login', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(2500);
await page.fill('input[type="email"]', 'demo@pernote.local');
await page.fill('input[type="password"]', 'demo1234');
page.on('request', (r) => { if (r.url().includes('/api/')) console.log('REQ:', r.postData()?.slice(0, 200) ?? '(no body)'); });
page.on('response', async (r) => { if (r.url().includes('/api/')) console.log('RESP:', r.status(), (await r.text().catch(() => '')).slice(0, 220)); });
await page.click('button[type="submit"]');
await page.waitForTimeout(6000);
await browser.close();
