/* merge pages → stored storage format (pageBreak separators + kinds) */
export function buildBookletDoc() {
  const pages = buildBookletPages();
  const blocks = [];
  pages.forEach((pg, i) => {
    if (i > 0) blocks.push(PB(pg.kind));
    blocks.push(...pg.blocks);
  });
  const doc = { type: 'doc', content: blocks };
  if (pages[0].kind !== 'framed') doc.attrs = { pageKind: pages[0].kind };
  return doc;
}
