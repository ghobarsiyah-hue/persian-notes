/**
 * Builder for the 30-page booklet «راهنمای کامل پرشین‌نوت» — a feature tour
 * written WITH the site's own tools. A4 usable height ≈ 950px at 16px/2.0,
 * so a full page ≈ 29 lines ≈ 7 paragraphs of ~2.6 rendered lines each.
 * Storage format: pageBreak nodes separate the pages; the first page's
 * visual kind rides on doc.attrs.pageKind, later pages' kinds ride on the
 * pageBreak that OPENS them.
 */

/* ── text helpers ──────────────────────────────────────────────────── */
const T = (t, marks) => (marks ? { type: 'text', marks, text: t } : { type: 'text', text: t });
const B = (t) => T(t, [{ type: 'bold' }]);
const U = (t) => T(t, [{ type: 'underline' }]);
const HIL = (t) => T(t, [{ type: 'highlight', attrs: { color: '#fde68a' } }]);
const CODE = (t) => T(t, [{ type: 'code' }]);
const P = (t, marks) => ({ type: 'paragraph', content: [T(t, marks)] });
const PR = (runs) => ({ type: 'paragraph', content: runs });
const H = (lvl, t, align) => ({
  type: 'heading',
  attrs: { level: lvl, textAlign: align || 'right' },
  content: [T(t)],
});
const HC = (lvl, t) => H(lvl, t, 'center');
const BQ = (t) => ({ type: 'blockquote', content: [P(t)] });
const HR = () => ({ type: 'horizontalRule' });
const PB = (kind) => (kind ? { type: 'pageBreak', attrs: { kind } } : { type: 'pageBreak' });

/* task items with real checkbox state */
const TODO = (checked, runs) => ({
  type: 'taskItem',
  attrs: { checked },
  content: [PR(runs)],
});
const TODOLIST = (items) => ({ type: 'taskList', content: items });

/* marks builders for inline feature demos */
const COL = (t, color) => T(t, [{ type: 'textStyle', attrs: { color } }, { type: 'bold' }]);
const FS = (t, size) => T(t, [{ type: 'textStyle', attrs: { fontSize: `${size}px` } }]);
const FF = (t, fam) => T(t, [{ type: 'textStyle', attrs: { fontFamily: fam } }]);
const SUP = (t) => T(t, [{ type: 'superscript' }]);
const SUB = (t) => T(t, [{ type: 'subscript' }]);
const LINK = (t, href) => T(t, [{ type: 'link', attrs: { href } }]);
const ICON = (ch, color) => ({
  type: 'inlineIcon',
  attrs: { char: ch, color: color || '#1e3a5f' },
});

/* ── table helpers (attrs mirror Page.tsx Table.extend + TableHeader) ─ */
const TH = (t, w) => ({
  type: 'tableHeader',
  attrs: { colspan: 1, rowspan: 1, ...(w ? { colwidth: [w] } : {}), backgroundColor: '#1e3a5f' },
  content: [P(t)],
});
const TD = (t) => ({ type: 'tableCell', attrs: { colspan: 1, rowspan: 1 }, content: [P(t)] });
const ROW = (cells) => ({ type: 'tableRow', content: cells });
function TABLE(tstyle, rows, width) {
  return {
    type: 'table',
    attrs: { striped: false, borderless: false, tstyle, align: 'center', width: width || '100%' },
    content: rows,
  };
}

/* ── edu block helpers (attrs mirror blocks.ts) ────────────────────── */
const CALLOUT = (kind, title, paras) => ({
  type: 'calloutBlock',
  attrs: { kind, title },
  content: paras,
});
const QUESTION = (q, paras) => ({ type: 'questionBlock', attrs: { question: q }, content: paras });
const EXAMPLE = (title, paras) => ({ type: 'exampleBlock', attrs: { title }, content: paras });
const KEYTERM = (term, paras) => ({ type: 'keyTermBlock', attrs: { term }, content: paras });
const FORMULA = (latex) => ({
  type: 'formulaBlock',
  content: [{ type: 'text', text: latex }],
});
const COMPARISON = (left, right, rows) => ({
  type: 'comparisonTable',
  attrs: { leftLabel: left, rightLabel: right },
  content: rows.map(([l, r]) => ({ type: 'row', content: [P(l), P(r)] })),
});
const TIMELINE = (title, items) => ({
  type: 'timeline',
  attrs: { title },
  content: items.map((t) => P(t)),
});
const FOOTNOTE = (label, paras) => ({ type: 'footnoteBlock', attrs: { label }, content: paras });
const LONGANSWER = (q, points, paras) => ({
  type: 'longAnswerBlock',
  attrs: { question: q, points },
  content: paras,
});
const HLBOX = (title, paras) => ({ type: 'highlightBox', attrs: { title, icon: '◉' }, content: paras });
const REFERENCE = (title, authors, year, url) => ({
  type: 'referenceBlock',
  attrs: { title, authors, year, url },
  content: [P('مرجع ثبت‌شده در کتابخانهٔ جزوه.')],
});
const PROCON = (topic, pro, con) => ({
  type: 'proConBlock',
  attrs: { topic, proText: pro, conText: con },
  content: [P('جمع‌بندی شما دربارهٔ موضوع:')],
});
const CODEOUT = (label, lang, code, out) => ({
  type: 'codeOutputBlock',
  attrs: { label, lang, codeText: code, outText: out },
  content: [P('کد بالا را اجرا کنید تا خروجی را ببینید.')],
});

/* ── equations (raw latex payloads — the node view heals via sanitizeAst,
      and renderHTML now heals too: parity with the live surface) ─────── */
const EQ = (latex, display = true) => ({
  type: 'equation',
  attrs: { ast: [{ type: 'latex', latex }], display, mode: 'professional', numbered: false, align: null },
});
const EQI = (latex) => ({
  type: 'equationInline',
  attrs: { ast: [{ type: 'latex', latex }], display: false, mode: 'professional' },
});
const EQRUN = (latex) => ({
  type: 'equation',
  attrs: { ast: [{ type: 'run', text: latex }], display: true, mode: 'professional', numbered: false, align: null },
});

