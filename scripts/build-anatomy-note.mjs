const dataUri = (raw) => `data:image/svg+xml;charset=utf-8,${encodeURIComponent(raw)}`;
const icon = (name) => ({
  type: 'inlineIcon',
  attrs: { src: dataUri(svg(name)), alt: name, title: name },
});

/* ── inline builders ──────────────────────────────────────────────────── */
const SAHEL = 'ساحل';
const TANHA = 'تنها';
const HEAD_MARKS = [
  { type: 'textStyle', attrs: { fontFamily: TANHA, fontSize: '18px' } },
  { type: 'bold' },
];
const TS = { type: 'textStyle', attrs: { fontFamily: SAHEL, fontSize: '16px' } };

/* idempotent: روی هر نود متن، مارک ساحل 16px را تضمین می‌کند (بدون تکرار) */
const withSahel = (node) =>
  node.type === 'text'
    ? { ...node, marks: [...(node.marks ?? []).filter((m) => m.type !== 'textStyle'), TS] }
    : node;

const t = (text, extra) =>
  withSahel({ type: 'text', text, ...(extra ? { marks: extra } : {}) });

const para = (content) => ({
  type: 'paragraph',
  attrs: { textAlign: null, indent: 0 },
  content: (Array.isArray(content) ? content : [t(content)]).map(withSahel),
});
const p = (content, opts = {}) => ({
  type: 'paragraph',
  attrs: { textAlign: opts.align ?? null, indent: opts.indent ?? 0 },
  content: content ? para(content).content : undefined,
});

/* تیتر با آیکون + فونت تنها 18px بولد (آیکون جایگزین متن نیست) */
const H = (level, iconName, text) => ({
  type: 'heading',
  attrs: { level, textAlign: null, indent: 0 },
  content: [icon(iconName), { type: 'text', text, marks: [...HEAD_MARKS] }],
});

/* ── real lists ───────────────────────────────────────────────────────── */
/* هر آیتم: string | آرایه‌ای از نودهای inline | { text, children } برای تودرتو */
const bullet = (items, marker = '') => ({
  type: 'bulletList',
  attrs: { marker, textAlign: null },
  content: items.map((i) =>
    i && typeof i === 'object' && i.children
      ? { type: 'listItem', content: [para(i.text), bullet(i.children, marker)] }
      : { type: 'listItem', content: [para(i)] },
  ),
});
const numbered = (items) => ({
  type: 'orderedList',
  attrs: { textAlign: null },
  content: items.map((i) => ({ type: 'listItem', content: [para(i)] })),
});

/* ── edu boxes ────────────────────────────────────────────────────────── */
/* باکس نکته — خانواده calloutBlock سایت (definition/important/exam/...) */
const note = (title, children, kind = 'important') => ({
  type: 'calloutBlock',
  attrs: { kind, title },
  content: children,
});
/* باکس سوال — questionBlock سایت با پاسخ مخفی‌شدنی (showAnswer) */
const question = (question, answer, opts = {}) => ({
  type: 'questionBlock',
  attrs: {
    question,
    answerText: answer,
    points: opts.points ?? 0,
    qVariant: opts.v ?? 'v1',
    showAnswer: opts.show ?? true,
    answerAt: 'mark',
    qAccent: '', qChip: '', qGap: '',
    styleBg: '', styleBorder: '', styleBorderWidth: -1, styleBorderStyle: '', styleRadius: -1, styleTitle: '',
  },
  content: [p()],
});

