const fa = (n) => String(n).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[+d]);
let phNo = 0;
function makePlaceholder(label) {
  phNo += 1;
  const w = 720, h = 420;
  const font = 'Vazirmatn, Tahoma, sans-serif';
  const raw =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">` +
    `<rect x="2" y="2" width="${w - 4}" height="${h - 4}" rx="14" fill="#eef2f7"/>` +
    `<rect x="2" y="2" width="${w - 4}" height="${h - 4}" rx="14" fill="none" stroke="#7a8aa0" stroke-width="2" stroke-dasharray="10 7"/>` +
    `<g fill="none" stroke="#9aa8ba" stroke-width="3" stroke-linecap="round" stroke-linejoin="round">` +
    `<rect x="${w / 2 - 32}" y="${h / 2 - 92}" width="64" height="50" rx="6"/>` +
    `<circle cx="${w / 2 - 14}" cy="${h / 2 - 76}" r="6"/>` +
    `<path d="M ${w / 2 - 26} ${h / 2 - 50} L ${w / 2 - 8} ${h / 2 - 70} L ${w / 2 + 6} ${h / 2 - 56} L ${w / 2 + 16} ${h / 2 - 64} L ${w / 2 + 26} ${h / 2 - 50}"/>` +
    `</g>` +
    `<text x="${w / 2}" y="${h / 2 + 6}" text-anchor="middle" font-family="${font}" font-size="26" font-weight="bold" fill="#41506b">محل قرارگیری تصویر</text>` +
    `<text x="${w / 2}" y="${h / 2 + 44}" text-anchor="middle" font-family="${font}" font-size="20" fill="#5d6b83">${label}</text>` +
    `<text x="${w / 2}" y="${h - 20}" text-anchor="middle" font-family="${font}" font-size="15" fill="#8492a8">تصویر ${fa(phNo)} — این قسمت بعداً Import می‌شود</text>` +
    `</svg>`;
  return {
    type: 'image',
    attrs: {
      src: dataUri(raw),
      alt: `Image Placeholder — ${label}`,
      title: label,
      width: null,
      align: 'center',
    },
  };
}
const ph = (i) => makePlaceholder(PLACEHOLDER_NAMES[i - 1]);

