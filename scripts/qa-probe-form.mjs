import { chromium } from 'playwright-core';
const browser = await chromium.launch();
const page = await browser.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push('PAGEERR: ' + e.message.slice(0, 160)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('CONSOLE: ' + m.text().slice(0, 160)); });
await page.goto('http://localhost:5173/login', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(2500);
await page.fill('input[type="email"]', 'demo@pernote.local');
await page.fill('input[type="password"]', 'demo1234');
const respPromise = page.waitForResponse((r) => r.url().includes('/api/auth/login'), { timeout: 20000 }).catch(() => null);
await page.click('button[type="submit"]');
const resp = await respPromise;
console.log('login response:', resp ? resp.status() + ' ' + resp.url() : 'NO-REQUEST-FIRED');
await page.waitForTimeout(3000);
console.log('url:', page.url());
console.log('formErr text:', await page.locator('[role="alert"]').first().textContent().catch(() => '(none)'));
errs.slice(0, 8).forEach((e) => console.log(e));
await browser.close();
